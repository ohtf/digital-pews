// Explicit, offline import of a reviewed OHTF website checkout. Never run at build time.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_REPOSITORY = 'https://github.com/ohtf/openhealthtechnology.org-website';
const SOURCE_FILES = ['mkdocs.yml', 'docs/stylesheets/extra.css', 'docs/assets/ohtf-mark.svg'];
const sha256 = data => createHash('sha256').update(data).digest('hex');

// Extract whole top-level mappings, not individual YAML values. This preserves
// the upstream theme settings verbatim and fails if their structure changes.
export function configurationBlock(config, key) {
  const match = config.match(new RegExp(`^${key}:\\n(?:[ \\t]+[^\\n]*(?:\\n|$)|[ \\t]*\\n)*`, 'm'));
  if (!match) throw new Error(`Missing upstream ${key} mapping`);
  return match[0].trimEnd();
}

export function sharedConfiguration(config) {
  let theme = configurationBlock(config, 'theme');
  if (!theme.includes('  variant: modern') || !theme.includes('  logo: assets/ohtf-mark.svg') ||
      !theme.includes('  favicon: assets/ohtf-mark.svg')) throw new Error('Review the changed upstream theme structure before importing');
  // Main-site landing/adviser templates are content, not the shared theme.
  theme = theme.replace(/^  custom_dir: overrides\n/m, '')
    .replaceAll(': assets/ohtf-mark.svg', ': ohtf/ohtf-mark.svg');
  if (theme.includes('custom_dir:')) throw new Error('Unexpected upstream custom template directory');
  return `# SPDX-FileCopyrightText: 2026 Open Health Technology Foundation contributors
# SPDX-License-Identifier: CC-BY-SA-4.0
# Generated by s/sync-ohtf-theme. Keep project content, nav and licensing outside this file.
${theme}

${configurationBlock(config, 'extra')}

extra_css:
  - ohtf/ohtf.css
`;
}

export function syncTheme(source, { check = false } = {}) {
  const git = args => execFileSync('git', args, { cwd: source, encoding: 'utf8' }).trim();
  const remote = git(['remote', 'get-url', 'origin']);
  if (!/github\.com[:/]ohtf\/openhealthtechnology\.org-website(?:\.git)?\/?$/.test(remote)) {
    throw new Error('Source origin must be the official OHTF website repository');
  }
  if (git(['status', '--porcelain', '--', ...SOURCE_FILES])) throw new Error('Commit the upstream branding changes before importing them');
  const revision = git(['rev-parse', 'HEAD']);
  const inputs = new Map(SOURCE_FILES.map(file => [file, readFileSync(path.join(source, file))]));
  const base = sharedConfiguration(inputs.get('mkdocs.yml').toString());
  const manifest = {
    schemaVersion: 1,
    sourceRepository: SOURCE_REPOSITORY,
    sourceRevision: revision,
    license: 'CC-BY-SA-4.0',
    sourceFiles: Object.fromEntries([...inputs].map(([file, data]) => [file, sha256(data)])),
    files: {
      'base.yml': sha256(base),
      'assets/ohtf.css': sha256(inputs.get('docs/stylesheets/extra.css')),
      'assets/ohtf-mark.svg': sha256(inputs.get('docs/assets/ohtf-mark.svg')),
    },
  };
  const outputs = new Map([
    ['base.yml', base],
    ['assets/ohtf.css', inputs.get('docs/stylesheets/extra.css')],
    ['assets/ohtf-mark.svg', inputs.get('docs/assets/ohtf-mark.svg')],
    ['manifest.json', `${JSON.stringify(manifest, null, 2)}\n`],
  ]);
  for (const [file, content] of outputs) {
    const destination = path.join(ROOT, 'theme/ohtf', file);
    if (check) {
      if (!readFileSync(destination).equals(Buffer.from(content))) throw new Error(`Theme differs from pinned upstream: ${file}`);
    } else {
      mkdirSync(path.dirname(destination), { recursive: true });
      writeFileSync(destination, content);
    }
  }
  console.log(`${check ? 'Verified' : 'Imported'} OHTF branding from ${revision}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const sources = args.filter(arg => arg !== '--check');
  if (sources.length !== 1 || sources[0].startsWith('-')) throw new Error('Usage: s/sync-ohtf-theme [--check] /path/to/openhealthtechnology.org-website');
  syncTheme(path.resolve(sources[0]), { check: args.includes('--check') });
}
